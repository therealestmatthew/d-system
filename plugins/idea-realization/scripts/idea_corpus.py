def _parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    paths.add_arguments(common, PATH_KEYS)
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    def command(name: str, help_text: str) -> argparse.ArgumentParser:
        return sub.add_parser(name, help=help_text, parents=[common])

    command("locate", "print where the sweep's files live; exit 1 if the staging directory "
                      "is not gitignored")
    command("start", "resume a sweep in progress, or move an earlier sweep's files aside")
    built = command("build", "write the corpus files and manifest")
    built.add_argument("--status", default=DEFAULT_STATUS,
                       help="status or comma-separated statuses to select (default: triaged)")
    built.add_argument("--seed", type=int, help="the build's seed; drawn at random if omitted")
    built.add_argument("--out", type=Path,
                       help="output directory (default: <staging>/corpus in the primary checkout)")
    built.add_argument("--exclude", type=Path,
                       help="file of idea ids to leave out, one per line; none by default")
    built.add_argument("--stats", action="store_true", help="print the manifest; write nothing")
    prompted = command("prompt", "print one pack section, filled in, and save it as sent")
    prompted.add_argument("section", choices=SECTIONS)
    prompted.add_argument("--draft", type=Path, help="the synthesis draft (S and A2)")
    reported = command("report", "write an agent's returned report under the run stamp")
    reported.add_argument("section", choices=sorted(REPORTS))
    reported.add_argument("--file", type=Path, required=True, help="the returned text")
    named = command("name", "print the draft's markdown and record paths")
    named.add_argument("date", help="the corpus date, from locate")
    checked = command("check", "check the draft and its record against the corpus")
    checked.add_argument("markdown", type=Path)
    checked.add_argument("record", type=Path)
    accepted = command("accept", "copy the accepted pair into the partitions directory")
    accepted.add_argument("markdown", type=Path)
    accepted.add_argument("record", type=Path)
    return parser


def _locate(where: Layout) -> int:
    ignored = is_ignored(where.staging)
    print(f"primary: {where.primary}")
    print(f"staging: {where.staging}")
    print(f"corpus: {where.corpus}")
    print(f"partitions: {where.partitions}")
    print(f"primary_status: {status_digest(where.primary)}")
    manifest = read_manifest(where.corpus)
    if manifest is not None:
        print(f"corpus_size: {manifest['corpus_size']} | status: {','.join(manifest['status'])}"
              f" | seed: {manifest['shuffle_seed']} | corpus date: {corpus_date(where.corpus)}")
        print(f"stamp: {run_stamp(manifest)}")
    if not ignored:
        print(f"refused: {where.staging} is not gitignored in {where.primary}", file=sys.stderr)
        return 1
    print("staging ignored: yes")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    where = layout(paths.resolve(args))
    try:
        if args.command == "locate":
            return _locate(where)
        if args.command == "start":
            print("\n".join(start(where)))
        elif args.command == "build":
            facts = build(where.idea_log, args.out or where.corpus, parse_statuses(args.status),
                          args.exclude, args.seed, args.stats)
            if args.stats:
                print(json.dumps(facts, indent=2))
            else:
                print(f"corpus size: {facts['corpus_size']} (of {facts['selected']} selected)")
                print(f"excluded: {len(facts['excluded'])}")
                print(f"layered evidence (>1 finding): {len(facts['layered_evidence'])}")
                print(f"seed: {facts['shuffle_seed']}")
                print(f"written to {args.out or where.corpus}")
        elif args.command == "prompt":
            sys.stdout.write(prompt(where, args.section, args.draft))
        elif args.command == "report":
            print(f"wrote {write_report(where, args.section, args.file.read_text('utf-8'))}")
        elif args.command == "name":
            note, markdown, record = name(where, args.date)
            if note:
                print(note)
            print(markdown)
            print(record)
        elif args.command == "check":
            problems = check_pair(args.markdown, args.record, where.corpus)
            for problem in problems:
                print("FAIL", problem)
            print(f"{len(problems)} problem(s)")
            return 1 if problems else 0
        else:
            for path in accept(where, args.markdown, args.record):
                print(f"wrote {path}")
    except (CorpusError, IdeaError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
