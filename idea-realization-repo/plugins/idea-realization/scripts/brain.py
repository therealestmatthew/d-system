"""The team's shared memory: decisions, research, concepts, entities and learnings.

Each entry is one markdown file with YAML front matter (``schemas/brain-entry.schema.json``) under
``brain_root``, in the folder for its kind. The front matter names its author's handle, so a team
on separate machines writes to one shared memory and every entry says who wrote it. Everything is
plain markdown: any model or person can read it, and git carries it.

Commands:

- ``new <kind> --title ...`` records an entry in one step, as the current developer, and
  regenerates the index.
- ``load`` prints the entries an agent should read, filtered by kind, tag, link or text, as one
  markdown block to read at the start of a session.
- ``index`` regenerates ``<brain_root>/index.md``. The check fails while it is stale.
- ``check`` reports every problem: front matter, folders, duplicate ids, broken links, the index.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from jsonschema import Draft7Validator, FormatChecker

sys.path.insert(0, str(Path(__file__).resolve().parent))

import identity  # noqa: E402
import paths  # noqa: E402

SCHEMA = paths.PLUGIN_ROOT / "schemas" / "brain-entry.schema.json"
INDEX = "index.md"
README = "README.md"
#: The folder each kind lives in.
FOLDERS = {
    "decision": "decisions", "research": "research", "concept": "concepts", "entity": "entities",
    "lesson": "learnings", "procedure": "learnings", "note": "learnings",
}
FRONT = re.compile(r"\A---\n(.*?)\n---\n?(.*)\Z", re.DOTALL)
DEFAULT_LIMIT = 20


@dataclass(frozen=True)
class Entry:
    path: Path
    meta: dict[str, Any]
    body: str

    @property
    def id(self) -> str:
        return str(self.meta.get("id", self.path.stem))


def entry_paths(root: Path) -> list[Path]:
    """Every entry file: markdown under a kind folder, never the README or the index."""
    folders = sorted(set(FOLDERS.values()))
    return sorted(path for folder in folders for path in (root / folder).glob("*.md"))


def parse(path: Path) -> tuple[Entry | None, str | None]:
    """An entry, or the reason its file cannot be read as one."""
    text = path.read_text(encoding="utf-8")
    match = FRONT.match(text)
    if not match:
        return None, "has no YAML front matter between --- lines"
    try:
        meta = yaml.safe_load(match.group(1))
    except yaml.YAMLError as exc:
        return None, f"front matter is not YAML: {exc}"
    if not isinstance(meta, dict):
        return None, "front matter is not a mapping"
    # YAML reads an unquoted date as a date; the schema describes the text form.
    meta = {key: value.isoformat() if isinstance(value, dt.date) else value
            for key, value in meta.items()}
    return Entry(path, meta, match.group(2)), None


def load_entries(root: Path) -> tuple[list[Entry], list[str]]:
    """Every readable entry, and one problem line per file that is not."""
    entries, errors = [], []
    for path in entry_paths(root):
        entry, error = parse(path)
        if error:
            errors.append(f"{relative(root, path)}: {error}")
        elif entry:
            entries.append(entry)
    return entries, errors


def relative(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def render_index(entries: list[Entry]) -> str:
    """The index: every entry by kind, newest change first within a kind."""
    lines = ["# Brain index", "",
             "Generated by `brain.py index`. Never edit by hand; `brain.py check` fails while it "
             "is stale.", ""]
    for kind, folder in FOLDERS.items():
        mine = [entry for entry in entries if entry.meta.get("kind") == kind]
        if not mine:
            continue
        lines += [f"## {kind}", "", "| Entry | Author | Updated | Status |", "|---|---|---|---|"]
        for entry in sorted(mine, key=lambda e: (str(e.meta.get("updated", "")), e.id),
                            reverse=True):
            lines.append(f"| [{entry.meta.get('title', entry.id)}]({folder}/{entry.path.name}) "
                         f"| {entry.meta.get('author', '')} | {entry.meta.get('updated', '')} "
                         f"| {entry.meta.get('status', '')} |")
        lines.append("")
    if len(lines) == 4:
        lines += ["No entries yet.", ""]
    return "\n".join(lines)


def problems(config: paths.Config) -> list[str]:
    """Every problem in the brain, one line each; none when it does not exist."""
    root = config.path("brain_root")
    if not root.is_dir():
        return []
    entries, errors = load_entries(root)
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    validator = Draft7Validator(schema, format_checker=FormatChecker())
    owners = known_owners(config)
    seen: dict[str, str] = {}
    for entry in entries:
        where = relative(root, entry.path)
        issues = [f"{where}:{'.'.join(map(str, issue.absolute_path))}: {issue.message}"
                  for issue in validator.iter_errors(entry.meta)]
        errors += issues
        if issues:
            continue
        if entry.id != entry.path.stem:
            errors.append(f"{where}: id {entry.id!r} is not the file name")
        if entry.path.parent.name != FOLDERS[entry.meta["kind"]]:
            errors.append(f"{where}: kind {entry.meta['kind']} belongs in "
                          f"{FOLDERS[entry.meta['kind']]}/")
        if owners is not None and entry.meta["author"] not in owners:
            errors.append(f"{where}: author {entry.meta['author']!r} is not in systems.yaml owners")
        if entry.id in seen:
            errors.append(f"{where}: duplicate id {entry.id} (also {seen[entry.id]})")
        seen[entry.id] = where
    for entry in entries:
        for link in entry.meta.get("links") or []:
            if link not in seen:
                errors.append(f"{relative(root, entry.path)}: links to unknown entry {link}")
    index = root / INDEX
    if not index.is_file() or index.read_text(encoding="utf-8") != render_index(entries):
        errors.append(f"{INDEX} is stale; run brain.py index and commit it")
    return sorted(errors)


def known_owners(config: paths.Config) -> set[str] | None:
    """The owner keys in systems.yaml, or None when there is no registry to check against."""
    registry = config.path("docs_root") / identity.REGISTRY
    if not registry.is_file():
        return None
    loaded = yaml.safe_load(registry.read_text(encoding="utf-8")) or {}
    return set((loaded.get("owners") or {}).keys())


def slug(title: str) -> str:
    words = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return "-".join(words.split("-")[:8]) or "entry"


def write_index(root: Path) -> Path:
    entries, _ = load_entries(root)
    index = root / INDEX
    index.write_text(render_index(entries), encoding="utf-8")
    return index


def new(config: paths.Config, kind: str, title: str, body: str, tags: list[str],
        links: list[str], sources: list[str], status: str = "active") -> Path:
    """Record one entry as the current developer and regenerate the index. Returns its path."""
    author = identity.handle(config)
    root = config.path("brain_root")
    entry_id = slug(title)
    path = root / FOLDERS[kind] / f"{entry_id}.md"
    if path.exists():
        raise ValueError(f"{relative(root, path)} exists; choose a more specific title")
    today = dt.date.today().isoformat()
    meta: dict[str, Any] = {"id": entry_id, "kind": kind, "title": title, "author": author,
                            "created": today, "updated": today, "status": status}
    for key, values in (("tags", tags), ("links", links), ("sources", sources)):
        if values:
            meta[key] = values
    issues = list(Draft7Validator(json.loads(SCHEMA.read_text(encoding="utf-8"))).iter_errors(
        meta))
    if issues:
        raise ValueError("; ".join(issue.message for issue in issues))
    known = {entry.id for entry in load_entries(root)[0]}
    unknown = [link for link in links if link not in known]
    if unknown:
        raise ValueError(f"links to unknown entries: {', '.join(unknown)}")
    path.parent.mkdir(parents=True, exist_ok=True)
    front = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True).strip()
    path.write_text(f"---\n{front}\n---\n\n{body.strip()}\n", encoding="utf-8")
    write_index(root)
    return path


def select(entries: list[Entry], kind: str | None = None, tag: str | None = None,
           link: str | None = None, query: str | None = None,
           include_superseded: bool = False) -> list[Entry]:
    """The entries matching every filter given. ``link`` selects that entry, the entries it
    links to and the entries that link to it."""
    by_id = {entry.id: entry for entry in entries}
    chosen = []
    for entry in entries:
        meta = entry.meta
        if not include_superseded and meta.get("status") == "superseded":
            continue
        if kind and meta.get("kind") != kind:
            continue
        if tag and tag not in (meta.get("tags") or []):
            continue
        if link:
            target = by_id.get(link)
            related = (entry.id == link or link in (meta.get("links") or [])
                       or (target is not None and entry.id in (target.meta.get("links") or [])))
            if not related:
                continue
        if query:
            text = f"{meta.get('title', '')}\n{' '.join(meta.get('tags') or [])}\n{entry.body}"
            if query.lower() not in text.lower():
                continue
        chosen.append(entry)
    return sorted(chosen, key=lambda e: (str(e.meta.get("updated", "")), e.id), reverse=True)


def render_context(root: Path, entries: list[Entry]) -> str:
    """One markdown block: each entry's title, kind, author, path and body."""
    if not entries:
        return "No brain entries match.\n"
    blocks = [f"# Brain context ({len(entries)} entries)"]
    for entry in entries:
        meta = entry.meta
        sources = ", ".join(meta.get("sources") or []) or "none"
        blocks.append(f"## [{meta.get('kind')}] {meta.get('title')}\n"
                      f"*{relative(root, entry.path)} | author {meta.get('author')} | updated "
                      f"{meta.get('updated')} | sources: {sources}*\n\n{entry.body.strip()}")
    return "\n\n".join(blocks) + "\n"


def _list(value: str | None) -> list[str]:
    return [part.strip() for part in (value or "").split(",") if part.strip()]


@paths.exits_on_path_error
def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Record, load and check the team's shared "
                                                 "memory.")
    commands = parser.add_subparsers(dest="command", required=True)
    record = commands.add_parser("new", help="record one entry as the current developer")
    record.add_argument("kind", choices=sorted(FOLDERS))
    record.add_argument("--title", required=True)
    record.add_argument("--body", default="", help="markdown body; '-' reads standard input")
    record.add_argument("--tags", help="comma-separated")
    record.add_argument("--links", help="comma-separated entry ids")
    record.add_argument("--sources", help="comma-separated URLs, documents or ids")
    record.add_argument("--status", choices=("active", "draft"), default="active")
    read = commands.add_parser("load", help="print the entries an agent should read")
    read.add_argument("--kind", choices=sorted(FOLDERS))
    read.add_argument("--tag")
    read.add_argument("--link", help="an entry id: it, what it links to, and what links to it")
    read.add_argument("--query", help="text to find in titles, tags and bodies")
    read.add_argument("--limit", type=int, default=DEFAULT_LIMIT)
    read.add_argument("--include-superseded", action="store_true")
    commands.add_parser("index", help="regenerate the index")
    commands.add_parser("check", help="report every problem")
    for sub in commands.choices.values():
        paths.add_arguments(sub, ["brain_root", "docs_root"])
    args = parser.parse_args(argv)
    config = paths.resolve(args)
    root = config.path("brain_root")
    if args.command == "new":
        body = sys.stdin.read() if args.body == "-" else args.body
        try:
            path = new(config, args.kind, args.title, body, _list(args.tags), _list(args.links),
                       _list(args.sources), args.status)
        except (identity.IdentityError, ValueError) as error:
            print(f"error: {error}", file=sys.stderr)
            return 1
        print(f"recorded {relative(root, path)}; commit it with {INDEX}")
        return 0
    if args.command == "load":
        entries, _ = load_entries(root) if root.is_dir() else ([], [])
        chosen = select(entries, args.kind, args.tag, args.link, args.query,
                        args.include_superseded)
        print(render_context(root, chosen[: max(args.limit, 0)]), end="")
        return 0
    if args.command == "index":
        if not root.is_dir():
            print(f"error: {root} does not exist; run the scaffold's brain feature",
                  file=sys.stderr)
            return 1
        print(f"wrote {relative(config.root, write_index(root))}")
        return 0
    found = problems(config)
    for line in found:
        print(line)
    return 1 if found else 0


def _command(argv: list[str]) -> int:
    return main(argv)


COMMANDS = {"brain": ("record, load or check the team's shared memory", _command)}

if __name__ == "__main__":
    raise SystemExit(main())
