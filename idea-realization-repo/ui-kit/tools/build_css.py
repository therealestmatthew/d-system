#!/usr/bin/env python3
"""Bundle the ui-kit stylesheets into `ui-kit/dist/ui.css`.

`dist/ui.css` is the one file a page or the React app loads. It is the concatenation, in this
fixed order, of:

    dist/tokens.css                 generated by build_tokens.py
    src/css/base.css                reset, type, focus ring, reduced motion
    src/css/layout.css              the app shell grid and report page
    dist/layouts.css                generated from layouts/*.json, when that tool exists
    src/css/components/*.css        one file per component, sorted by file name

A part that does not exist yet is skipped, so the bundle builds while the kit is incomplete;
the header lists exactly the parts it contains. Each part is preceded by a comment naming it.
No clock or environment is read and output is LF-terminated UTF-8, so the bundle is
byte-identical on every rebuild.

    uv run python ui-kit/tools/build_css.py           # rewrite dist/ui.css
    uv run python ui-kit/tools/build_css.py --check   # exit 1 if dist/ui.css is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
OUTPUT = KIT / "dist" / "ui.css"
FIXED_PARTS = ("dist/tokens.css", "src/css/base.css", "src/css/layout.css", "dist/layouts.css")
COMPONENTS = "src/css/components"


def parts(kit: Path = KIT) -> list[str]:
    """The kit-relative paths that go into the bundle, in bundle order, existing ones only."""
    found = [p for p in FIXED_PARTS if (kit / p).is_file()]
    component_dir = kit / COMPONENTS
    if component_dir.is_dir():
        found += sorted(f"{COMPONENTS}/{p.name}" for p in component_dir.glob("*.css"))
    return found


def render(kit: Path = KIT) -> str:
    """The bundle text."""
    included = parts(kit)
    if "dist/tokens.css" not in included:
        raise FileNotFoundError("dist/tokens.css is missing; run build_tokens.py first")
    lines = [
        "/*",
        "  ui-kit stylesheet bundle. GENERATED: do not edit by hand.",
        "  Regenerate: uv run python ui-kit/tools/build_css.py",
        "  Parts, in order:",
        *(f"    {p}" for p in included),
        "*/",
        "",
    ]
    out = "\n".join(lines)
    for p in included:
        body = (kit / p).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
        out += f"\n/* ---- {p} ---- */\n{body}\n"
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Bundle the ui-kit stylesheets.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the bundle is stale")
    args = parser.parse_args(argv)
    try:
        text = render()
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if current != text:
            print(f"{OUTPUT} is stale; run build_css.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} matches its parts")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(parts())} parts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
